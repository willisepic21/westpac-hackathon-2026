"""Make app-sized copies of the wallpapers.

The originals in wallpapers/ are ~4000x3000 photos (31 MB total), too heavy to bundle into the app or show 23 at
once in a picker. This writes, for every wallpapers/<n>.jpg:
  assets/wallpapers/full/<n>.jpg   shortest side 1080 px  (Home background)
  assets/wallpapers/thumb/<n>.jpg  shortest side 240 px   (picker grid)
Then regenerates src/personalise/wallpapers.js, which lists them for Metro (require() needs literal paths).

Run from the project root after adding or changing wallpapers:  python scripts/resize_wallpapers.py
"""

from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "wallpapers"
OUT = ROOT / "assets" / "wallpapers"
SIZES = {"full": (1080, 70), "thumb": (240, 70)}  # shortest side, JPEG quality


def main():
    numbers = sorted(int(p.stem) for p in SRC.glob("*.jpg") if p.stem.isdigit())
    for folder, (short_side, quality) in SIZES.items():
        (OUT / folder).mkdir(parents=True, exist_ok=True)
        for n in numbers:
            with Image.open(SRC / f"{n}.jpg") as img:
                img = ImageOps.exif_transpose(img).convert("RGB")  # respect phone rotation
                scale = short_side / min(img.size)
                if scale < 1:
                    img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
                img.save(OUT / folder / f"{n}.jpg", "JPEG", quality=quality, optimize=True, progressive=True)

    lines = [
        "// Generated by scripts/resize_wallpapers.py from the wallpapers/ folder. Don't edit by hand.",
        "// Wallpaper n (1-based) = customisation.wallpaper in the database; 0 = no wallpaper.",
        "",
        "export const WALLPAPERS = [",
    ]
    for n in numbers:
        lines.append(
            f"  {{ id: {n}, full: require('../../assets/wallpapers/full/{n}.jpg'), "
            f"thumb: require('../../assets/wallpapers/thumb/{n}.jpg') }},"
        )
    lines += ["];", ""]
    (ROOT / "src" / "personalise" / "wallpapers.js").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    total = sum(p.stat().st_size for p in OUT.rglob("*.jpg"))
    print(f"{len(numbers)} wallpapers -> {OUT} ({total / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
